// The short guide written next to openapi.json.
import { EDGE_FUNCTIONS } from './edge-functions.mjs';

/**
 * @param {{ host: string, version: string, counts: ReturnType<import('./spec.mjs').summarize>, deployed: Map<string, boolean | null> }} input
 */
export function renderReadme({ host, version, counts, deployed }) {
  const base = `https://${host}`;
  const warnings = EDGE_FUNCTIONS.filter((fn) => fn.warning).map((fn) => `- \`${fn.name}\`: ${fn.warning}`);
  const notDeployed = [...deployed].filter(([, isDeployed]) => isDeployed === false).map(([name]) => `\`${name}\``);

  return `# XO Platform API

Generated by \`npm run api:openapi\` (version ${version}). Do not edit by hand.

| File | Use |
|---|---|
| \`openapi.json\` | Swagger 2.0 description. Import into Postman (Import → File) or any OpenAPI tool. |
| \`index.html\` | Open in a browser to read the API (Swagger UI). |

## What is inside

| Group | Count |
|---|---|
| Tables & views | ${counts.tables} |
| SQL functions used by the app | ${counts.rpcUsed} |
| Other SQL functions (helpers, server-only) | ${counts.rpcOther} |
| Server functions for apps | ${counts.functionsApp} |
| Internal server functions | ${counts.functionsInternal} |

## Calling the API

Base URL: \`${base}\`. Every request sends \`apikey: <public anon key>\`; after signing in, also \`Authorization: Bearer <access_token>\`.

1. Sign in:
   \`\`\`
   POST ${base}/auth/v1/token?grant_type=password
   { "email": "...", "password": "..." }
   \`\`\`
2. Read rows (row-level security limits them to what the user may see):
   \`\`\`
   GET ${base}/rest/v1/children?select=id,full_name_ar,full_name_en&status=eq.active
   \`\`\`
3. Call a SQL function:
   \`\`\`
   POST ${base}/rest/v1/rpc/get_attendance_kpis
   \`\`\`
4. Call a server function:
   \`\`\`
   POST ${base}/functions/v1/qr-verify
   { "token": "..." }
   \`\`\`

Official client libraries handle these headers: supabase-js (React Native), supabase-flutter, supabase-swift, supabase-kotlin.

## Rules

- Never put the service-role (secret) key in an app.
- Money and attendance changes go through the SQL functions (for example \`submit_invoice_payment\`), not direct table writes.
- A breaking change to a function gets a new name (\`..._v2\`); the old one stays until no app version uses it. Mobile users update late.
- "Other SQL functions" and internal server functions are not part of the app API.

## Known issues

${[...warnings, notDeployed.length ? `- Not deployed in production: ${notDeployed.join(', ')}.` : null].filter(Boolean).join('\n')}
`;
}
